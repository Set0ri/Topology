// Coverage Map Computation Helper
export function getTopologyCoverageMetrics(): CoverageMetrics {
  const totalArchetypes = CANONICAL_ARCHETYPES.length;
  const readyCount = CANONICAL_ARCHETYPES.filter(a => a.status === 'ready').length;
  const roadmapCount = CANONICAL_ARCHETYPES.filter(a => a.status === 'roadmap').length;
  const overallCoveragePercent = Math.round((readyCount / totalArchetypes) * 100);

  const categories: ('coding' | 'knowledge' | 'reasoning' | 'operations')[] = [
    'coding',
    'knowledge',
    'reasoning',
    'operations',
  ];

  const categoryLabels: Record<string, string> = {
    coding: 'Coding & Dev Loops',
    knowledge: 'Knowledge & RAG',
    reasoning: 'Multi-Agent Reasoning',
    operations: 'Operations & SRE',
  };

  const categoryBreakdown = categories.map(cat => {
    const total = CANONICAL_ARCHETYPES.filter(a => a.category === cat).length;
    const ready = CANONICAL_ARCHETYPES.filter(a => a.category === cat && a.status === 'ready').length;
    const percent = total > 0 ? Math.round((ready / total) * 100) : 100;
    return {
      category: cat,
      label: categoryLabels[cat],
      ready,
      total,
      percent,
    };
  });

  return {
    totalArchetypes,
    readyCount,
    roadmapCount,
    overallCoveragePercent,
    categoryBreakdown,
  };
}
